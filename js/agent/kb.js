// ------------------------------ 5. 知识问答主入口 ------------------------------
function agentKBHandle(text) {
  var t = String(text || '');
  if (!t) return false;
  if (!agentKBIsKnowledgeQuery(t)) return false;

  var qtype = agentKBClassify(t);

  // ① 对比类优先（"A 和 B 有什么区别"）
  //    注意：why/impact 类问句若同时含"区别"也应按对比处理，因为用户是在比两个东西
  var cmp = agentKBParseCompare(t);
  if (cmp && qtype !== 'why') {
    var ra = agentKBRetrieve(cmp.a, 1)[0];
    var rb = agentKBRetrieve(cmp.b, 1)[0];
    // 若一侧没检索到，反过来在整句里再找一次
    if (!ra) ra = agentKBRetrieve(t, 2)[0];
    if (!rb) rb = agentKBRetrieve(t, 2)[1];
    if (ra && rb && ra.kb.id !== rb.kb.id) {
      return agentKBAnswerCompare(ra.kb, rb.kb);
    }
  }

  // ② 单条知识
  var hits = agentKBRetrieve(t, 3);
  if (hits.length) {
    var h0 = hits[0], h1 = hits[1];
    // 多概念并列 → 走对比，但必须满足两个前提：
    //   (a) 两条都被「整词提及」（否则只是子串误命中，如"货币基金"里的"基金"）；
    //   (b) 二者不构成父子概念关系（货币基金 vs 基金 是包含，不是并列对比）。
    var bothMentioned = h1 && agentKBHeadwordHit(h1.kb, t) && agentKBHeadwordHit(h0.kb, t);
    var parentChild = h1 && (agentKBIsSubconceptOf(h0.kb, h1.kb) || agentKBIsSubconceptOf(h1.kb, h0.kb));
    var nearTie = h1 && h1.score >= 8 && h1.score >= h0.score * 0.7;

    // v8 因果 / 影响类问句 → 三段式分析卡（为什么发生 / 对我什么影响 / 怎么处理）
    var wantsAnalysis = (qtype === 'why' || qtype === 'impact');
    if (wantsAnalysis && h0.kb.why && h0.kb.why.length) {
      return agentKBWhyAnswer(h0.kb, t);
    }

    if (!wantsAnalysis && bothMentioned && !parentChild && nearTie) {
      return agentKBAnswerCompare(h0.kb, h1.kb);
    }
    return agentKBAnswerItem(h0.kb, t, { qtype: qtype });
  }

  // ③ 检索不到：交给下游（模型层/场景层），不要硬编
  return false;
}

// ------------------------------ 6. 工具注册 ------------------------------
registerAgentTool('kb.search', {
  label: '检索金融知识库', risk: 'low',
  run: function (args) {
    var q = (args && args.query) || '';
    var hits = agentKBRetrieve(q, 3);
    if (!hits.length) return { summary: '知识库中未找到相关条目', data: [] };
    var qtype = agentKBClassify(q);
    var detail = hits.map(function (h) {
      return {
        id: h.kb.id, title: h.kb.title, cat: FIN_KB_META[h.kb.cat],
        risk: h.kb.risk, liquidity: h.kb.liquidity, yieldText: h.kb.yieldText,
        points: h.kb.points,
        why: h.kb.why || [],         // 原因分析（用于回答"为什么"）
        impact: h.kb.impact || [],   // 对个人的影响（用于回答"对我有什么影响"）
        fit: h.kb.fit || '',         // 适合人群
        advices: h.kb.advices || []
      };
    });
    return {
      summary: '检索到 ' + hits.length + ' 条相关知识（问题类型：' + qtype + '）：' + hits.map(function (h) { return h.kb.title; }).join('、'),
      questionType: qtype,
      data: detail
    };
  }
});
