// v8 对个人的影响（结合真实数据）：把知识条目的 impact 与用户自身财务状况挂钩
// 额外从条目自身的 why（原因分析）里，捞出直接点到用户身上的子项，补进影响列表，
//   保证"利率变化会影响什么"能落到 房贷 / 消费贷 / 企业融资 这种具体传导上。
function agentKBImpactItems(item) {
  var list = (item.impact || []).slice();
  var borrowers = /房贷|消费贷|贷款|借款|月供|融资|负债|债/;
  (item.why || []).forEach(function (w) {
    if (borrowers.test(w) && list.indexOf(w) < 0) list.push(w);
  });
  return list;
}

// "结合你的数据"小节（只有真实数据命中时才渲染）
function agentKBPersonalDataBlock() {
  var ctx = agentKBUserContext();
  var personal = [];
  if (ctx.savingRate !== null && ctx.savingRate < 0.2) {
    personal.push('你的储蓄率目前约 ' + Math.round(ctx.savingRate * 100) + '%，低于 20% 的健康线，抗风险缓冲偏薄');
  }
  if (ctx.debtRatio !== null && ctx.debtRatio >= 0.4) {
    personal.push('你月供占收入约 ' + Math.round(ctx.debtRatio * 100) + '%，已进入偿债警戒区，利率变动对你的冲击会比一般人更大');
  }
  if (ctx.riskLevel) {
    personal.push('你的风险承受等级为 ' + ctx.riskLevel + '，配置时以该等级为上限');
  }
  if (!personal.length) return '';
  return '<div class="kb-why-personal"><span class="kb-why-personal-label">结合你的数据</span>' +
    personal.map(function (p) { return '<div class="kb-why-personal-line">· ' + p + '</div>'; }).join('') + '</div>';
}

function agentKBPersonalImpact(item) {
  if (!item.impact || !item.impact.length) return '';
  var items = agentKBImpactItems(item);
  return '<div class="agent-sec-title">对你的影响</div>' +
    '<div class="kb-why-list">' +
    items.map(function (x) { return '<div class="kb-why-item">· ' + x + '</div>'; }).join('') +
    '</div>' + agentKBPersonalDataBlock();
}

// v8 读取用户背景（供影响分析使用），字段缺失时返回 null，避免瞎编
function agentKBUserContext() {
  var ctx = { savingRate: null, debtRatio: null, riskLevel: null, surplus: null, balance: null };
  try {
    var month = (typeof agentMonthSummary === 'function') ? agentMonthSummary() : null;
    if (month) {
      ctx.surplus = month.balance || 0;
      if (month.income > 0 && typeof month.balance === 'number') ctx.savingRate = month.balance / month.income;
    }
  } catch (e) { /* 忽略 */ }
  try {
    if (typeof agentSessionSnapshot === 'function') {
      var snap = agentSessionSnapshot();
      if (snap && typeof snap.balance === 'number') ctx.balance = snap.balance;
    }
  } catch (e) { /* 忽略 */ }
  try {
    if (typeof AGENT_MEMORY !== 'undefined' && AGENT_MEMORY && AGENT_MEMORY.riskLevel) ctx.riskLevel = AGENT_MEMORY.riskLevel;
    else if (typeof AGENT_MEMORY !== 'undefined' && AGENT_MEMORY && AGENT_MEMORY.profile && AGENT_MEMORY.profile.riskAttr) {
      ctx.riskLevel = AGENT_MEMORY.profile.riskAttr.level || null;
    }
  } catch (e) { /* 忽略 */ }
  return ctx;
}

// v8 "为什么 / 影响" 三段式回答：基础解释 → 原因分析 → 对用户影响 → 处理建议
